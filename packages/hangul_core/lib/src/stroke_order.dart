/// 자모 **획순** — 몇 개의 선분이 한 획인지.
///
/// ## 왜 표가 필요한가 (2026-09-10 실측)
///
/// jammin 자모 SVG 는 글리프를 선분(`<line>`/`<path>`)으로 그려 놓았고, 그
/// **선분 수가 정통 획수와 다르다**. 40개 자모 중 25개만 우연히 같았다:
///
/// - **모음은 거의 그대로 맞는다**(ㅏ 2/2 · ㅐ 3/3 · ㅘ 4/4 …)
/// - **자음은 꺾이는 획이 쪼개져 있다** — ㄱ 은 선분 2개지만 **1획**이고(붓을 떼지
///   않는다), ㅇ 은 선분 4개지만 1획, ㅎ 은 6개지만 3획이다
///
/// 그래서 선분을 그대로 "획"이라 부르면 **초등학생에게 틀린 획수를 가르치게 된다.**
/// 자동으로 끌어낼 수 없으니 **명시적으로 적는다.**
///
/// ## 이 표가 맞는지 어떻게 아나
///
/// 두 가지가 동시에 맞아야 한다(`stroke_order_test.dart` 가 검사한다):
///
///   1. `sum(groups) == 자산의 실제 선분 수`  ← 앱 쪽 테스트가 SVG 를 읽어 대조
///   2. `groups.length == 정통 획수`          ← 아래 [strokeCount]
///
/// 하나만 맞으면 표가 틀린 것이다.
///
/// ## ⚠️한계
///
/// **획을 긋는 방향은 이 표가 말해 주지 않는다.** 선분의 시작·끝점은 자산 제작자가
/// 정한 것이라 교육적 방향(예: 가로획은 왼→오른쪽)과 반대일 수 있다. 그래서 화면은
/// **"어느 획을 먼저 긋는가"까지만** 안내하고 방향 화살표는 붙이지 않는다.
library;

/// 자모별 **획순 그룹** — 앞에서부터 이만큼씩 묶으면 한 획이다.
///
/// 예) `'ㄷ': [1, 2]` = 첫 선분이 1획(윗 가로), 다음 두 선분이 묶여 2획(ㄴ 모양).
///
/// 여기 없는 자모는 **선분 하나가 곧 한 획**이다(대부분의 모음, ㅂ·ㅅ·ㅍ 등).
const Map<String, List<int>> strokeGroups = {
  // ── 자음: 꺾이는 획이 선분으로 쪼개져 있다 ──
  'ㄱ': [2], // 가로 + 세로를 붙여 한 번에 긋는다
  'ㄲ': [2, 2],
  'ㄴ': [2],
  'ㄷ': [1, 2],
  'ㄸ': [1, 2, 1, 2],
  'ㄹ': [2, 1, 2], // ㄱ + ㅡ + ㄴ
  'ㅁ': [1, 2, 1], // 왼세로 + (윗가로·오른세로) + 아랫가로
  'ㅇ': [4], // 원은 한 획인데 자산은 사분원 4개다
  'ㅈ': [1, 2],
  'ㅉ': [1, 2, 1, 2],
  'ㅊ': [1, 1, 2], // 점 + 가로 + ㅅ… 이 아니라 점·가로·(ㅅ묶음)
  'ㅋ': [2, 1],
  'ㅌ': [1, 1, 2],
  'ㅎ': [1, 1, 4], // 점 + 가로 + 원(사분원 4개)
};

/// 정통 획수 — 초등 교육과정 기준. [strokeGroups] 의 **검산용**이다.
const Map<String, int> strokeCount = {
  'ㄱ': 1, 'ㄲ': 2, 'ㄴ': 1, 'ㄷ': 2, 'ㄸ': 4, 'ㄹ': 3, 'ㅁ': 3, 'ㅂ': 4,
  'ㅃ': 8, 'ㅅ': 2, 'ㅆ': 4, 'ㅇ': 1, 'ㅈ': 2, 'ㅉ': 4, 'ㅊ': 3, 'ㅋ': 2,
  'ㅌ': 3, 'ㅍ': 4, 'ㅎ': 3,
  'ㅏ': 2, 'ㅐ': 3, 'ㅑ': 3, 'ㅒ': 4, 'ㅓ': 2, 'ㅔ': 3, 'ㅕ': 3, 'ㅖ': 4,
  'ㅗ': 2, 'ㅘ': 4, 'ㅙ': 5, 'ㅚ': 3, 'ㅛ': 3, 'ㅜ': 2, 'ㅝ': 4, 'ㅞ': 5,
  'ㅟ': 3, 'ㅠ': 3, 'ㅡ': 1, 'ㅢ': 2, 'ㅣ': 1,
};

/// 선분 [segments] 개를 획 단위로 묶는다 → 각 획이 몇 번째 선분들인지.
///
/// 표에 없으면 **선분 하나 = 한 획**으로 본다.
/// 표와 실제 선분 수가 어긋나면(자산이 바뀌었다) 표를 믿지 않고 1:1 로 떨어뜨린다 —
/// 잘못 묶어 엉뚱한 획순을 보여 주느니 안내를 포기하는 편이 낫다.
List<List<int>> groupSegments(String letter, int segments) {
  final groups = strokeGroups[letter];
  if (groups == null || groups.fold(0, (a, b) => a + b) != segments) {
    return [for (var i = 0; i < segments; i++) [i]];
  }
  final out = <List<int>>[];
  var cursor = 0;
  for (final n in groups) {
    out.add([for (var i = 0; i < n; i++) cursor + i]);
    cursor += n;
  }
  return out;
}

/// 이 자모의 획순 안내를 **믿을 수 있는가**.
///
/// 표에 있고 검산이 맞을 때만 참이다. 거짓이면 UI 는 "획순"이라 말하지 않고
/// 부위별 보기 정도로만 쓴다 — 틀린 획수를 가르치지 않기 위해서다.
bool isStrokeOrderKnown(String letter, int segments) {
  final expected = strokeCount[letter];
  if (expected == null) return false;
  final groups = strokeGroups[letter];
  if (groups == null) return segments == expected;
  return groups.fold(0, (a, b) => a + b) == segments &&
      groups.length == expected;
}
